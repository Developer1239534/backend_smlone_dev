function getBranch(id) {
  if (id.startsWith('7') && id.length > 4) return 'tritura';
  if (id.startsWith('9') && id.length > 4) return 'cemara';
  const num = parseInt(id, 10);
  if (!isNaN(num) && num >= 1 && num <= 1000) return 'cp';
  return 'cp';
}

async function main() {
  // De-duplicate by ID (keep first)
  const seen = new Set();
  const uniqueData = [];
  for (const row of rawData) {
    if (!seen.has(row.id)) {
      seen.add(row.id);
      uniqueData.push(row);
    }
  }

  console.log(`🚀 Total UNIQUE trainee IDs with Referral Codes: ${uniqueData.length}`);

  let updatedPortal = 0;
  let updatedLogin = 0;

  for (const { id, code } of uniqueData) {
    const branch = getBranch(id);
    const plainPassword = `SML${id}`;
    const hashedPassword = await bcrypt.hash(plainPassword, 10);

    await db.query(`
      INSERT INTO portal_trainee (trainee_id, branch_id, referral_code, updated_at)
      VALUES ($1, $2, $3, NOW())
      ON CONFLICT (trainee_id) DO UPDATE
      SET referral_code = EXCLUDED.referral_code,
          branch_id = COALESCE(portal_trainee.branch_id, EXCLUDED.branch_id),
          updated_at = NOW();
    `, [id, branch, code]);
    updatedPortal++;

    await db.query(`
      INSERT INTO login_trainee (student_id, password, plain_password, updated_at)
      VALUES ($1, $2, $3, NOW())
      ON CONFLICT (student_id) DO UPDATE
      SET password = EXCLUDED.password,
          plain_password = EXCLUDED.plain_password,
          updated_at = NOW();
    `, [id, hashedPassword, plainPassword]);
    updatedLogin++;
  }

  console.log('--- Summary Results ---');
  console.log(`✅ portal_trainee updated with referral_code: ${updatedPortal}`);
  console.log(`✅ login_trainee synced:                      ${updatedLogin}`);

  const sample = await db.query(`
    SELECT trainee_id, branch_id, referral_code
    FROM portal_trainee
    WHERE referral_code IS NOT NULL
    LIMIT 6;
  `);
  console.log('--- Sample Records ---');
  console.table(sample.rows);
}

main().catch(err => {
  console.error('❌ Import error:', err);
  process.exit(1);
});
