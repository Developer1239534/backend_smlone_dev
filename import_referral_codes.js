async function main() {
  console.log('🚀 Importing Referral Codes into portal_trainee & login_trainee...');

  const lines = rawData.split('\n').map(l => l.trim()).filter(Boolean);
  const entries = [];

  for (const line of lines) {
    const parts = line.split('\t').map(p => p.trim());
    // Format: ID  REFERRAL CODE  <code>
    if (parts.length < 3) continue;
    const id = parts[0];
    const code = parts[parts.length - 1];
    if (!id || !code || code === 'REFERRAL CODE') continue;
    entries.push({ id, code });
  }

  // Deduplicate: keep LAST occurrence per ID
  const codeMap = new Map();
  for (const e of entries) {
    codeMap.set(e.id, e.code);
  }

  console.log(`📌 Total raw entries parsed: ${entries.length}`);
  console.log(`📌 Unique Trainee IDs (deduplicated): ${codeMap.size}`);

  let portalUpdated = 0;
  let loginUpserted = 0;

  for (const [id, code] of codeMap.entries()) {
    // 1. Upsert portal_trainee referral_code
    await db.query(`
      INSERT INTO portal_trainee (trainee_id, referral_code, updated_at)
      VALUES ($1, $2, CURRENT_TIMESTAMP)
      ON CONFLICT (trainee_id) DO UPDATE SET
        referral_code = EXCLUDED.referral_code,
        updated_at = CURRENT_TIMESTAMP;
    `, [id, code]);
    portalUpdated++;

    // 2. Upsert login_trainee (SML + ID)
    const plainPassword = `SML${id}`;
    const hash = await bcrypt.hash(plainPassword, 10);
    await db.query(`
      INSERT INTO login_trainee (student_id, password, plain_password, updated_at)
      VALUES ($1, $2, $3, CURRENT_TIMESTAMP)
      ON CONFLICT (student_id) DO UPDATE SET
        password = EXCLUDED.password,
        plain_password = EXCLUDED.plain_password,
        updated_at = CURRENT_TIMESTAMP;
    `, [id, hash, plainPassword]);
    loginUpserted++;
  }

  console.log('\n🎉 SUCCESSFUL REFERRAL CODE IMPORT:');
  console.log(`- portal_trainee records updated (referral_code): ${portalUpdated}`);
  console.log(`- login_trainee accounts upserted: ${loginUpserted}`);

  // Final verification
  const portalCount = await db.query('SELECT COUNT(*) FROM portal_trainee');
  const rcCount = await db.query('SELECT COUNT(*) FROM portal_trainee WHERE referral_code IS NOT NULL');
  const loginCount = await db.query('SELECT COUNT(*) FROM login_trainee');

  console.log('\n📊 Final Database Verification:');
  console.log(`- Total rows in portal_trainee: ${portalCount.rows[0].count}`);
  console.log(`- Trainees with referral_code: ${rcCount.rows[0].count}`);
  console.log(`- Total rows in login_trainee: ${loginCount.rows[0].count}`);

  process.exit(0);
}

